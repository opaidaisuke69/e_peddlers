    /**
     * Helper: Extract Active Auth Token from GET or Authorization Header
     */
    private static function getAuthToken(): string {
        $token = trim($_GET['token'] ?? '');
        if ($token === '' || $token === 'undefined' || $token === 'null') {
            $headers = getallheaders();
            $authHeader = $headers['Authorization'] ?? $headers['authorization'] ?? '';
            if (preg_match('/Bearer\s(\S+)/', $authHeader, $matches)) {
                $token = trim($matches[1]);
            }
        }
        return $token;
    }

    /**
     * Helper: Format JSON Audit Log Details into Clean Human-Readable Summary
     */
    public static function formatLogDetails(?string $raw): string {
        if (!$raw || trim($raw) === '' || $raw === '[]' || $raw === '{}') return '—';
        $decoded = json_decode($raw, true);
        if (is_array($decoded)) {
            $parts = [];
            foreach ($decoded as $k => $v) {
                if (is_array($v)) {
                    $v = json_encode($v, JSON_UNESCAPED_SLASHES);
                } elseif (is_bool($v)) {
                    $v = $v ? 'true' : 'false';
                } elseif ($v === null) {
                    $v = 'null';
                }
                $label = ucwords(str_replace('_', ' ', (string)$k));
                $parts[] = "{$label}: {$v}";
            }
            return implode(' • ', $parts);
        }
        return (string)$raw;
    }

    /**
     * Helper: Stream Standardized CSV with UTF-8 BOM and Official Header Metadata
     */
    private static function streamCsv(string $filename, array $headers, array $dataRows, array $meta = [], ?array $totalsRow = null): void {
        header('Content-Type: text/csv; charset=utf-8');
        header('Content-Disposition: attachment; filename="' . $filename . '"');
        header('Pragma: no-cache');
        header('Expires: 0');

        $out = fopen('php://output', 'w');
        // UTF-8 BOM for MS Excel compatibility
        fwrite($out, "\xEF\xBB\xBF");

        // Metadata Header
        fputcsv($out, ['# REPUBLIC OF THE PHILIPPINES - CITY OF LA CARLOTA']);
        fputcsv($out, ['# E-PEDDLERS REGULATORY PLATFORM OFFICIAL SYSTEM REPORT']);
        if (!empty($meta['title'])) fputcsv($out, ['# Report Title:', $meta['title']]);
        if (!empty($meta['period'])) fputcsv($out, ['# Scope / Period:', $meta['period']]);
        if (!empty($meta['generated_by'])) fputcsv($out, ['# Generated By:', $meta['generated_by']]);
        fputcsv($out, ['# Generated Date:', date('Y-m-d H:i:s')]);
        fputcsv($out, []); // Blank separator line

        // Column Headers
        fputcsv($out, $headers);

        // Data Rows
        foreach ($dataRows as $row) {
            fputcsv($out, $row);
        }

        // Summary Totals
        if (!empty($totalsRow)) {
            fputcsv($out, []);
            fputcsv($out, $totalsRow);
        }

        fclose($out);
        exit;
    }

    /**
