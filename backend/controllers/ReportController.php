    /**
     * 3. SATURDAY MARKET VENDOR MAPPING & STALL OCCUPANCY REPORT
     */
    public static function marketStallReport(): void {
        $user = AuthMiddleware::authenticate();
        PlatformMiddleware::enforce($user, 'web');
        RoleMiddleware::authorize($user, ['admin', 'treasury']);

        $pdo = Database::getConnection();

        $sectionFilter = $_GET['section'] ?? 'all'; // 'all', 'A', 'B', 'C', 'D', 'E', 'F'
        $statusFilter = $_GET['status'] ?? 'all'; // 'all', 'AVAILABLE', 'OCCUPIED', 'RESERVED', 'RESTRICTED'
        $search = trim($_GET['search'] ?? '');
        $format = $_GET['format'] ?? 'json';
        $token = self::getAuthToken();

        $sql = "
            SELECT ms.id, ms.slot_code, ms.section_code, ms.section_name, ms.slot_number, ms.status,
                   ms.notes, ms.updated_at,
                   p.peddler_code, CONCAT(p.first_name, ' ', p.last_name) AS peddler_name,
                   p.phone AS peddler_phone, p.business_nature,
                   pa.application_number, CONCAT(pa.first_name, ' ', pa.last_name) AS applicant_name,
                   pa.nature_of_business AS app_business_nature
            FROM market_slots ms
            LEFT JOIN peddlers p ON ms.assigned_peddler_id = p.id
            LEFT JOIN permit_applications pa ON ms.assigned_application_id = pa.id
            WHERE 1=1
        ";
        $params = [];

        if ($sectionFilter !== 'all') {
            $sql .= " AND ms.section_code = ?";
            $params[] = $sectionFilter;
        }

        if ($statusFilter !== 'all') {
            $sql .= " AND ms.status = ?";
            $params[] = $statusFilter;
        }

        if ($search !== '') {
            $sql .= " AND (ms.slot_code LIKE ? OR ms.section_name LIKE ? OR p.first_name LIKE ? OR p.last_name LIKE ? OR pa.first_name LIKE ? OR pa.last_name LIKE ? OR p.peddler_code LIKE ?)";
            $s = "%{$search}%";
            $params = array_merge($params, [$s, $s, $s, $s, $s, $s, $s]);
        }

        $sql .= " ORDER BY ms.section_code ASC, ms.slot_number ASC";

        $stmt = $pdo->prepare($sql);
        $stmt->execute($params);
        $stalls = $stmt->fetchAll();

        // Summaries
        $totalStalls = count($stalls);
        $occupiedCount = 0;
        $availableCount = 0;
        $reservedCount = 0;
        $restrictedCount = 0;

        foreach ($stalls as $st) {
            $s = strtoupper($st['status']);
            if ($s === 'OCCUPIED') $occupiedCount++;
            elseif ($s === 'AVAILABLE') $availableCount++;
            elseif ($s === 'RESERVED') $reservedCount++;
            else $restrictedCount++;
        }

        $occupancyRate = $totalStalls > 0 ? round(($occupiedCount / $totalStalls) * 100, 1) : 0.0;
        $scopeLabel = ($sectionFilter !== 'all') ? "Section {$sectionFilter}" : "All Sections (A to F - 300 Slots)";
        $generatedBy = trim(($user['first_name'] ?? '') . ' ' . ($user['last_name'] ?? '')) ?: 'System Administrator';

        // CSV EXPORT
        if ($format === 'csv') {
            $csvRows = [];
            foreach ($stalls as $s) {
                $occupant = $s['peddler_name'] ?: ($s['applicant_name'] ?: 'None (Vacant)');
                $code = $s['peddler_code'] ?: ($s['application_number'] ?: '—');
                $nature = $s['business_nature'] ?: ($s['app_business_nature'] ?: '—');

                $csvRows[] = [
                    $s['slot_code'],
                    $s['section_code'],
                    $s['section_name'],
                    $s['slot_number'],
                    $s['status'],
                    $occupant,
                    $code,
                    $nature,
                    $s['peddler_phone'] ?: '—',
                    $s['notes'] ?: '—',
                ];
