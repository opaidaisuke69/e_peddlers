        $periodLabel = date('M d, Y', strtotime($startDate)) . ' to ' . date('M d, Y', strtotime($endDate));
        $generatedBy = trim(($user['first_name'] ?? '') . ' ' . ($user['last_name'] ?? '')) ?: 'System Administrator';

