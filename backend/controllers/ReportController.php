            $amt = (float)$p['amount_paid'];
            $totalPermit += $amt;
            if ($p['payment_method'] === 'CASH') $cashTotal += $amt;
            else $onlineTotal += $amt;
        }

        foreach ($arkabalaCollections as $a) {
            $amt = (float)$a['amount_paid'];
            $totalArkabala += $amt;
            if ($a['payment_method'] === 'CASH') $cashTotal += $amt;
            else $onlineTotal += $amt;
        }

