            $sql .= " AND (al.action LIKE ? OR al.details LIKE ? OR u.first_name LIKE ? OR u.last_name LIKE ? OR al.entity_id LIKE ?)";
            $s = "%{$search}%";
            $params = array_merge($params, [$s, $s, $s, $s, $s]);
