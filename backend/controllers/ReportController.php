                SELECT pp.id, pp.or_number, pp.payment_method, pp.amount_paid, pp.verified_at,
                       pa.application_number, CONCAT(pa.first_name, ' ', pa.last_name) AS payor_name,
                       pa.nature_of_business, 'PERMIT_FEE' AS transaction_type
                FROM permit_payments pp
                JOIN permit_applications pa ON pp.application_id = pa.id
                WHERE pp.status = 'VERIFIED'
                AND DATE(pp.verified_at) BETWEEN ? AND ?
            ";
            $params = [$startDate, $endDate];
            if ($methodFilter !== 'all') {
                $sql .= " AND pp.payment_method = ?";
                $params[] = $methodFilter;
            }
            $sql .= " ORDER BY pp.verified_at DESC";

            $stmtPermits = $pdo->prepare($sql);
            $stmtPermits->execute($params);
            $permitPayments = $stmtPermits->fetchAll();
        }

        if ($reportType === 'all' || $reportType === 'arkabala') {
            $sql = "
                SELECT ac.id, ac.receipt_number AS or_number, ac.payment_method, ac.amount AS amount_paid,
                       ac.collection_date AS verified_at, ac.transaction_code AS application_number,
                       CONCAT(p.first_name, ' ', p.last_name) AS payor_name,
                       p.business_nature, 'ARKABALA' AS transaction_type
                FROM arkabala_collections ac
                JOIN peddlers p ON ac.peddler_id = p.id
                WHERE ac.status = 'PAID'
                AND ac.collection_date BETWEEN ? AND ?
            ";
            $params = [$startDate, $endDate];
            if ($methodFilter !== 'all') {
                $m = ($methodFilter === 'PAYMONGO_QRPH') ? 'ONLINE' : $methodFilter;
                $sql .= " AND ac.payment_method = ?";
                $params[] = $m;
            }
            $sql .= " ORDER BY ac.collection_date DESC";

            $stmtArkabala = $pdo->prepare($sql);
            $stmtArkabala->execute($params);
            $arkabalaCollections = $stmtArkabala->fetchAll();
        }

