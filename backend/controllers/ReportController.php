        $sql = "
            SELECT p.id, p.peddler_code, p.first_name, p.middle_name, p.last_name, p.gender,
                   p.phone, p.email, p.business_nature, p.business_type, p.num_papag, p.num_lag_it,
                   p.status, p.is_qr_active, p.created_at,
                   pm.permit_number, pm.valid_from, pm.valid_until, pm.assigned_slot
            FROM peddlers p
            LEFT JOIN permits pm ON pm.peddler_id = p.id AND pm.status = 'active'
            WHERE 1=1
